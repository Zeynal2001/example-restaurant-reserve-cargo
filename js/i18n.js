let currentLang = 'az';

export function getCurrentLang() {
  return currentLang;
}

export function initI18n() {
  currentLang = localStorage.getItem('aura_lang') || 'az';
  applyLanguage(currentLang);
  setupLanguageDropdown();
}

export function applyLanguage(lang) {
  if (!TRANSLATIONS[lang]) lang = 'az';
  currentLang = lang;
  localStorage.setItem('aura_lang', lang);
  document.documentElement.lang = lang;

  const dict = TRANSLATIONS[lang];

  // Update all [data-i18n] text
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.innerHTML = dict[key];
    }
  });

  // Update input placeholders with [data-i18n-placeholder]
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) {
      el.setAttribute('placeholder', dict[key]);
    }
  });

  // Update active flags and labels
  const langLabel = document.getElementById('currentLangLabel');
  if (langLabel) {
    langLabel.textContent = lang.toUpperCase();
  }

  document.querySelectorAll('.lang-option').forEach(opt => {
    opt.classList.toggle('active', opt.dataset.lang === lang);
  });

  // Notify listeners to re-render dynamic localized components
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

function setupLanguageDropdown() {
  const btn = document.getElementById('langToggleBtn');
  const dropdown = document.getElementById('langDropdown');

  if (btn && dropdown) {
    btn.addEventListener('click', (e) => {
      e.stopPropagation();
      dropdown.classList.toggle('open');
    });

    document.querySelectorAll('.lang-option').forEach(opt => {
      opt.addEventListener('click', (e) => {
        e.stopPropagation();
        const selected = opt.dataset.lang;
        applyLanguage(selected);
        dropdown.classList.remove('open');
      });
    });

    document.addEventListener('click', () => {
      dropdown.classList.remove('open');
    });
  }
}
